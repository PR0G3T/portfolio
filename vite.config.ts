import adapter from '@sveltejs/adapter-static';
import tailwindcss from '@tailwindcss/vite';
import { sveltekit } from '@sveltejs/kit/vite';
import { defineConfig } from 'vite';

export default defineConfig({
	plugins: [
		tailwindcss(),
		sveltekit({
			adapter: adapter({
				pages: 'docs',
				assets: 'docs',
				fallback: undefined,
				precompress: false
			}),
			paths: {
				// The production site is served at the domain root (pr0g3t.com).
				// Set BASE_PATH only when deploying under a sub-path (e.g. /CV).
				base: (process.env.BASE_PATH ?? '') as '' | `/${string}`
			},
			prerender: {
				entries: ['*'],
				handleHttpError: ({ path, message }) => {
					// Generated by scripts/generate-pdfs.mjs immediately after the build.
					if (path === '/CV.pdf' || path === '/CV-fr.pdf') return;
					throw new Error(message);
				}
			}
		})
	]
});
